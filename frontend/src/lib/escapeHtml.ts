/** Escape nilai dinamis sebelum disisipkan ke string HTML (popup MapLibre/Leaflet `setHTML`). */
export function escapeHtml(value: unknown): string {
  return String(value ?? "").replace(/[&<>"']/g, (c) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c] as string),
  );
}
